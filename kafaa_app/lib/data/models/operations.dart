  final Badge badge;
  final String? periodLabel;
  final double? scoreValue;
  final bool isPublic;
  final DateTime? awardedAt;

  factory CenterBadge.fromMap(Map<String, dynamic> m) {
    final nested = m['badges'];
    return CenterBadge(
      id: asString(m['id']),
      centerId: asString(m['center_id']),
      badge: Badge.fromMap(
        nested is Map<String, dynamic> ? nested : <String, dynamic>{},
      ),
      periodLabel: asStringOrNull(m['period_label']),
      scoreValue: asDouble(m['score_value']),
      isPublic: asBool(m['is_public']),
      awardedAt: asDate(m['awarded_at']),
    );
  }
