class Ncr {
  const Ncr({
    required this.id,
    required this.code,
    required this.centerId,
    this.auditId,
    this.responseId,
    this.criterionId,
    required this.titleEn,
    this.titleAr,
    this.description,
    this.rootCause,
    required this.riskLevel,
    required this.priority,
    this.ownerId,
    this.ownerName,
    this.dueDate,
    required this.status,
    this.correctiveActionPlan,
    this.resolutionNotes,
    required this.isAutoGenerated,
    this.createdAt,
    this.closedAt,
  });

  final String id;
  final String code;
  final String centerId;
  final String? auditId;
  final String? responseId;
  final String? criterionId;
  final String titleEn;
  final String? titleAr;
  final String? description;
  final String? rootCause;
  final RiskLevel riskLevel;
  final int priority;
  final String? ownerId;
  final String? ownerName;
  final DateTime? dueDate;
  final NcrStatus status;
  final String? correctiveActionPlan;
  final String? resolutionNotes;
  final bool isAutoGenerated;
  final DateTime? createdAt;
  final DateTime? closedAt;

  int? get daysUntilDue {
    if (dueDate == null) return null;
    final today = DateTime.now();
    return DateTime(dueDate!.year, dueDate!.month, dueDate!.day)
        .difference(DateTime(today.year, today.month, today.day))
        .inDays;
  }

  bool get isOverdue =>
      status != NcrStatus.closed &&
      status != NcrStatus.resolved &&
      (daysUntilDue ?? 1) < 0;

  factory Ncr.fromMap(Map<String, dynamic> m) => Ncr(
        id: asString(m['id']),
        code: asString(m['code']),
        centerId: asString(m['center_id']),
        auditId: asStringOrNull(m['audit_id']),
        responseId: asStringOrNull(m['response_id']),
        criterionId: asStringOrNull(m['criterion_id']),
        titleEn: asString(m['title_en']),
        titleAr: asStringOrNull(m['title_ar']),
        description: asStringOrNull(m['description']),
        rootCause: asStringOrNull(m['root_cause']),
        riskLevel: RiskLevel.tryParse(asString(m['risk_level'])),
        priority: asIntOr(m['priority'], 3),
        ownerId: asStringOrNull(m['owner_id']),
        ownerName: asStringOrNull(m['owner_name']),
        dueDate: asDate(m['due_date']),
        status: NcrStatus.tryParse(asString(m['status'])),
        correctiveActionPlan: asStringOrNull(m['corrective_action_plan']),
        resolutionNotes: asStringOrNull(m['resolution_notes']),
        isAutoGenerated: asBool(m['is_auto_generated']),
        createdAt: asDate(m['created_at']),
        closedAt: asDate(m['closed_at']),
      );
}

